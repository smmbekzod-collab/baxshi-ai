final languageProvider = NotifierProvider<Language, String>(Language.new);

class Language extends Notifier<String> {
  @override
  String build() => 'uz';
  void set(String value) {
    if (const ['uz', 'kaa', 'en'].contains(value)) state = value;
  }
}

final themeProvider = NotifierProvider<AppTheme, ThemeMode>(AppTheme.new);

class AppTheme extends Notifier<ThemeMode> {
  @override
  ThemeMode build() => ThemeMode.system;
  void toggle() {
    state = state == ThemeMode.dark ? ThemeMode.light : ThemeMode.dark;
  }
}

